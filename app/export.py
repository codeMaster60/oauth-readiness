"""Markdown export: the same guide, pasteable into a PR, a Notion page or an agent's context."""

from .models import Guide

EV = {"tested": "✅ tested", "probed": "🛰️ probed live", "documented": "📄 official docs",
      "third_party": "🔗 third-party", "uncertain": "⚠️ uncertain"}
WHO = {"you": "You", "agent": "Agent", "either": "You or agent"}


def _cite(g: Guide, item) -> str:
    refs = []
    for sid in item.sources:
        s = g.source(sid)
        if s:
            refs.append(f"[{sid}]({s.url})")
    return f" — {EV[item.evidence]}" + (f" {' '.join(refs)}" if refs else "")


def to_markdown(g: Guide, base_url: str = "") -> str:
    v = g.verdict
    L = [f"# Getting a {g.name} OAuth app ready for production", ""]
    if g.use_case:
        L.append(f"_Assumes you want to: {g.use_case}._")
        L.append("")
    L += [
        f"**Difficulty {v.difficulty}/5 — {v.label}**  ",
        f"**Hands-on effort:** {v.active_effort} · **Waiting on {g.name}:** {v.wait}  ",
        f"**What usually blocks launch:** {v.gating_step}",
        "",
        v.summary,
        "",
    ]
    if g.concept:
        L += ["## How this fits together", "", g.concept, ""]
    c = g.composio
    L += ["## Do you need your own OAuth app?", "",
          f"Composio-managed app available: **{c.managed}**. {c.managed_note}", "",
          "Bring your own app when:"] + [f"- {x}" for x in c.when_own_app] + [
          "", f"Callback / redirect URL to register: `{c.redirect_uri}`", ""]
    if g.paths:
        L += ["## Your path depends on what you need", ""]
        for p in g.paths:
            L.append(f"- **{p.name}** ({p.difficulty}/5, wait {p.wait}): {p.when}{_cite(g, p)}")
        L.append("")
    for st in g.stages:
        L += [f"## {st.name}", ""]
        if st.summary:
            L += [st.summary, ""]
        for n in st.limits:
            L.append(f"> Limit: {n.text}{_cite(g, n)}")
        if st.limits:
            L.append("")
        for i, s in enumerate(st.steps, 1):
            mins = f" (~{s.minutes} min)" if s.minutes else ""
            L.append(f"{i}. [ ] **{s.title}** — {WHO[s.who]}{mins}{_cite(g, s)}")
            if s.detail:
                L.append(f"   {s.detail}")
        L.append("")
    if g.requirements:
        L += ["## Requirements", ""]
        for r in g.requirements:
            L.append(f"- **{r.item}** ({r.when}){': ' + r.detail if r.detail else ''}{_cite(g, r)}")
        L.append("")
    if g.gotchas:
        L += ["## Gotchas", ""]
        for x in g.gotchas:
            L.append(f"- **[{x.severity}] {x.title}** {x.detail}{_cite(g, x)}")
        L.append("")
    if g.blockers:
        L += ["## When you hit a blocker", ""]
        for b in g.blockers:
            L.append(f"- **{b.symptom}** — {b.cause} **Fix:** {b.fix}{_cite(g, b)}")
        L.append("")
    L += ["## What an agent can do vs. what you must do", "", "**Agent:**"]
    L += [f"- {x}" for x in g.agent_split.agent] + ["", "**You:**"] + [f"- {x}" for x in g.agent_split.you] + [""]
    if g.uncertainties:
        L += ["## Not verified / uncertain", ""] + [f"- {u}" for u in g.uncertainties] + [""]
    if g.probes:
        L += ["## Live probes", ""] + [f"- `{p.url}` — {p.observed}" for p in g.probes] + [""]
    L += ["## Sources", ""] + [f"- [{s.id}] [{s.title}]({s.url}) ({s.kind})" for s in g.sources] + [""]
    origin = "Hand-checked" if g.origin == "curated" else f"Generated by agent ({g.model})"
    L.append(f"_{origin} · updated {g.updated}" + (f" · {base_url}/guides/{g.slug}" if base_url else "") + "_")
    return "\n".join(L)
